#!/usr/bin/env python3
"""Generate ConciergeClock/<lang>.lproj/Localizable.strings from tools/translations/*.txt.

Each .txt line is `key | value`. Keys starting with `infoplist.` are the iPhone permission
prompts; they go to ConciergeClock/<lang>.lproj/InfoPlist.strings instead. English (en.txt) is
the reference: every language must have exactly the same keys and the same format
placeholders (%@, %d, %1$d ...). The script also checks that every key used in the Swift
code exists in English.

Same tool as PrepPilot, FocusFound and FotoPhilter (tools/generate_strings.py), adapted for
Concierge Clock. The shared texts (Settings basics, Offline AI and its setup guide, About Greater
Good Software) were copied from PrepPilot's translations; keep them in step when they change.

Run from the repository root:  python3 tools/generate_strings.py
"""
import collections, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "translations"
OUT = ROOT / "ConciergeClock"
SPEC = re.compile(r"%(?:(\d+)\$)?([@dfs])")
CODE_KEY = re.compile(r'(?:l10n|self|strings)(?:\[|\()"([A-Za-z0-9_.]+)"')
# App extensions get their own Localizable.strings with the keys under their prefix.
EXTENSIONS = {
    ROOT / "ConciergeClockWidgets": "widget.",
    # The butler's spoken phrases, read by ConciergeCore's BriefingBuilder in any language.
    ROOT / "Packages" / "ConciergeKit" / "Sources" / "ConciergeCore" / "Resources": "brief.",
    # The offline AI setup guide shared by all Greater Good Software apps (GGSModelKit).
    ROOT / "Packages" / "GGSModelKit" / "Sources" / "GGSModelUI" / "Resources": "guide.",
}
# Keys built at runtime (e.g. key + ".title") that the code scan cannot see.
DYNAMIC_PREFIXES = ("about.", "company.")

def load(path):
    entries = collections.OrderedDict()
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        if " | " not in line:
            sys.exit(f"{path.name}:{n}: expected 'key | value'")
        key, value = line.split(" | ", 1)
        key, value = key.strip(), value.strip()
        if key in entries:
            sys.exit(f"{path.name}:{n}: duplicate key {key}")
        entries[key] = value
    return entries

def placeholders(value):
    found = SPEC.findall(value)
    # Normalise: positional or not, compare the sorted list of (position, type).
    return sorted((int(pos) if pos else i + 1, kind) for i, (pos, kind) in enumerate(found))

# Info.plist permission texts (see Config/Info.plist) and the translation key for each.
# Microphone, Speech Recognition and Health texts are added with the phases that use them.
INFO_PLIST_KEYS = [
    ("NSAlarmKitUsageDescription", "infoplist.alarmKit"),
    ("NSCalendarsFullAccessUsageDescription", "infoplist.calendars"),
    ("NSRemindersFullAccessUsageDescription", "infoplist.reminders"),
    ("NSMicrophoneUsageDescription", "infoplist.microphone"),
    ("NSSpeechRecognitionUsageDescription", "infoplist.speech"),
]

def escape(value):
    return value.replace('"', '\\"')

reference = load(SRC / "en.txt")
errors = []

used = set()
for folder in [OUT, ROOT / "Shared", *EXTENSIONS]:
    for swift in folder.rglob("*.swift"):
        used.update(CODE_KEY.findall(swift.read_text(encoding="utf-8")))
# A key ending in "." is a prefix joined at runtime (e.g. "tool." + name).
missing_in_english = sorted(
    k for k in used if k not in reference and not k.endswith(".") and not k.startswith(DYNAMIC_PREFIXES)
)
if missing_in_english:
    errors.append(f"en: keys used in code but missing: {missing_in_english}")

languages = sorted(p.stem for p in SRC.glob("*.txt"))
for lang in languages:
    entries = load(SRC / f"{lang}.txt")
    missing = set(reference) - set(entries)
    extra = set(entries) - set(reference)
    if missing: errors.append(f"{lang}: missing {sorted(missing)}")
    if extra: errors.append(f"{lang}: unknown {sorted(extra)}")
    for key, value in entries.items():
        if key in reference and placeholders(value) != placeholders(reference[key]):
            errors.append(f"{lang}: placeholder mismatch in {key}: {value!r}")
    if errors:
        continue
    folder = OUT / f"{lang}.lproj"
    folder.mkdir(exist_ok=True)
    lines = ["/* Generated by tools/generate_strings.py — edit tools/translations/%s.txt instead. */" % lang, ""]
    lines += [f'"{k}" = "{escape(entries[k])}";' for k in reference if not k.startswith("infoplist.")]
    (folder / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")
    plist = ["/* Generated by tools/generate_strings.py — edit tools/translations/%s.txt instead. */" % lang, ""]
    for plist_key, key in INFO_PLIST_KEYS:
        plist.append(f'"{plist_key}" = "{escape(entries[key])}";')
    (folder / "InfoPlist.strings").write_text("\n".join(plist) + "\n", encoding="utf-8")
    for extension, prefix in EXTENSIONS.items():
        ext_folder = extension / f"{lang}.lproj"
        ext_folder.mkdir(parents=True, exist_ok=True)
        ext_lines = lines[:2] + [f'"{k}" = "{escape(entries[k])}";' for k in reference if k.startswith(prefix)]
        (ext_folder / "Localizable.strings").write_text("\n".join(ext_lines) + "\n", encoding="utf-8")

if errors:
    print("\n".join(errors)); sys.exit(1)
print(f"OK: {len(languages)} languages x {len(reference)} keys -> ConciergeClock/<lang>.lproj/Localizable.strings")
